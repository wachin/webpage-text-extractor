# ---------------------------------------------------------------------------
# Writer / compiler: renders per-locale .ts files from TRANSLATIONS and
# (optionally) compiles them to .qm with lrelease.
# ---------------------------------------------------------------------------

APP_ID = "webpage-text-extractor"


def write_translations() -> None:
    """Write translations/<locale>/webpage-text-extractor.ts for every locale."""
    for locale, strings in TRANSLATIONS.items():
        tree = ET.parse(BASE_TS)
        root = tree.getroot()
        for context in root.findall("context"):
            for message in context.findall("message"):
                source_el = message.find("source")
                if source_el is None or not source_el.text:
                    continue
                source = source_el.text
                if source in strings:
                    trans_el = message.find("translation")
                    if trans_el is None:
                        trans_el = ET.SubElement(message, "translation")
                    trans_el.text = strings[source]
                    trans_el.attrib.pop("type", None)
        out_dir = HERE / locale
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / "webpage-text-extractor.ts"
        tree.write(out_path, encoding="utf-8", xml_declaration=True)
        print(f"wrote {out_path}")


def compile_all() -> None:
    """Compile every <locale>/webpage-text-extractor.ts to
    translations/{APP_ID}_{locale}.qm with lrelease."""
    for locale in TRANSLATIONS:
        ts_path = HERE / locale / "webpage-text-extractor.ts"
        qm_path = HERE / f"{APP_ID}_{locale}.qm"
        try:
            subprocess.run(
                ["lrelease", str(ts_path), "-qm", str(qm_path)],
                check=True, capture_output=True, text=True,
            )
            print(f"compiled {qm_path}")
        except (subprocess.CalledProcessError, FileNotFoundError) as exc:
            print(f"lrelease failed for {locale}: {exc}")


def main() -> None:
    write_translations()
    if "--compile" in sys.argv:
        compile_all()


if __name__ == "__main__":
    main()